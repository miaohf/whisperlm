# 转录优化 Prompt
# 用于：ASR 错误修复、口语表达优化、语义断句/合并
# ──────────────────────────────────────────────────────────────────────────────
OPTIMIZE_PROMPT = """你是一个专业的字幕编辑，擅长对语音转录文本进行后处理。\
请对以下转录段落按要求进行优化。

语言：{language}

优化要求：
{features}

注意事项：
- 严格保持说话人的原意，不得添加或删除实质性内容
- 保持 speaker 字段不变
- 若合并相邻段落，start 取所有被合并段落的最小值，end 取最大值
- 时间戳保留两位小数
- 对于无法改善的段落，原样输出

输入段落（JSON 格式）：
{segments}

请以 JSON 数组格式输出优化后的段落，格式如下：
[{{"id": 0, "start": 0.0, "end": 1.0, "text": "优化后的文本", "speaker": "SPEAKER_00"}}]

直接输出 JSON 数组，不要包含任何说明文字或代码块标记。"""

